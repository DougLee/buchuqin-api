import fs from 'node:fs';
import assert from 'node:assert/strict';
import { call, state, save, q, items, root } from '../remote-night-acceptance/http.mjs';
const material = JSON.parse(fs.readFileSync(root + '/credentials.json', 'utf8'));
const orgs = items(await call('/api/v1/admin/organizations'));
assert.equal(orgs.find(row => row.id === state.organizationId)?.name, '夜宵部署验收20261107');
const staff = items(await call('/api/v1/admin/staff' + q(state.campusId))).find(row => row.id === state.mainStaffId);
assert.ok(staff && staff.role === 'building-manager');
state.mainStaffNo = staff.staffNo;
state.manager = await call('/api/v1/auth/staff-bind', 'POST', { code: `QA20261107:${material.authNonce}:manager`, appid: 'wx2026110700000002', staffNo: staff.staffNo, name: staff.name }, null, 200);
const context = await call('/api/v1/fulfillment/business-context', 'GET', undefined, state.manager.token);
assert.equal(context.canSwitchWorkspace, true);
state.parity ||= {};
state.parity.nightConfigBefore ||= await call('/api/v1/admin/night/config' + q(state.campusId));
state.parity.dayConfigBefore ||= await call('/api/v1/admin/delivery-config' + q(state.campusId));
save();
await call('/api/v1/admin/delivery-config' + q(state.campusId), 'PATCH', { manualClosed: true, closeStart: '00:00', closeEnd: '00:00', deliveryFeeInstant: 200, deliveryFeeScheduled: 100, deliveryThreshold: 0 });
await call('/api/v1/admin/night/config' + q(state.campusId), 'PUT', { campusId: state.campusId, nightEnabled: true, nightStartAt: '00:00', nightEndAt: '23:59', nightPayTimeout: 15, nightAcceptTimeout: 60, nightDeliveryFee: 200, confirm: true });
const store = await call('/api/v1/admin/night/stores/' + state.storeId + q(state.campusId));
if (store.status !== 'open') await call('/api/v1/night-rider/night/store/open', 'POST', undefined, state.manager.token);
state.catalog = items(await call('/api/v1/admin/night/catalog' + q(state.campusId)));
state.buyerAddressId = items(await call('/api/v1/addresses', 'GET', undefined, state.users.buyer.token)).find(row => row.buildingId === state.buildingId)?.id;
assert.ok(state.buyerAddressId); save();
console.log(JSON.stringify({ setup: 'passed', organization: '夜宵部署验收20261107', campusId: state.campusId, storeId: state.storeId, formalManager: context.canSwitchWorkspace, catalogCount: state.catalog.length, windowForTest: '00:00–23:59', stockOrMoneySeeded: false }));
